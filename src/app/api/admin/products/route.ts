import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import { productFormSchema } from "@/lib/admin/product-schema";
import { slugify, uniqueSlug } from "@/lib/admin/slugify";

// Клієнтка не вводить slug/SKU вручну (форма їх не показує) — генеруємо тут
// із назви товару. generateSlug бере вже зайняті slug з однаковим "коренем"
// із БД і додає суфікс через uniqueSlug; generateSku просто короткий
// випадковий код, унікальність перевіряє unique-констрейнт у БД (з retry
// нижче в POST, якщо випадково зіткнулись).
async function generateSlug(name: string): Promise<string> {
  const base = slugify(name);
  const existing = await prisma.product.findMany({
    where: { slug: { startsWith: base } },
    select: { slug: true },
  });
  return uniqueSlug(base, new Set(existing.map((p) => p.slug)));
}

function generateSku(): string {
  const random = Math.random().toString(36).slice(2, 6).toUpperCase();
  return `LMF-${Date.now().toString(36).toUpperCase()}${random}`;
}

export const dynamic = "force-dynamic";

// Адмін-CRUD товарів. Список для сторінки /admin/products читається напряму
// через Prisma в самому Server Component — цей GET лишається для повноти API.
export async function GET() {
  const products = await prisma.product.findMany({
    include: { images: true, variants: true, category: true },
    orderBy: { createdAt: "desc" },
  });
  return NextResponse.json(products);
}

export async function POST(request: Request) {
  const body = await request.json();
  const parsed = productFormSchema.safeParse(body);

  if (!parsed.success) {
    return NextResponse.json(
      { error: "Некоректні дані", issues: parsed.error.flatten() },
      { status: 400 }
    );
  }

  const { images, variants, slug: providedSlug, sku: providedSku, ...productFields } = parsed.data;

  // До 5 спроб: якщо автозгенерований slug/SKU випадково зіткнувся з уже
  // існуючим (гонка двох одночасних збережень), пробуємо згенерувати заново
  // — клієнтка про це не дізнається, бо поля їй все одно не показуються.
  for (let attempt = 0; attempt < 5; attempt += 1) {
    const slug = providedSlug?.trim() || (await generateSlug(productFields.name));
    const sku = providedSku?.trim() || generateSku();

    try {
      const product = await prisma.product.create({
        data: {
          ...productFields,
          slug,
          sku,
          images: {
            create: images.map((image, index) => ({
              url: image.url,
              alt: image.alt,
              position: index,
            })),
          },
          variants: {
            create: variants.map((variant) => ({
              sizeId: variant.sizeId,
              colorId: variant.colorId,
              stock: variant.stock,
            })),
          },
        },
        include: { images: true, variants: true },
      });
      return NextResponse.json(product, { status: 201 });
    } catch (error: any) {
      const isLastAttempt = attempt === 4;
      const wasAutoGenerated = !providedSlug?.trim() || !providedSku?.trim();
      if (error?.code === "P2002" && wasAutoGenerated && !isLastAttempt) continue;
      if (error?.code === "P2002") {
        return NextResponse.json(
          { error: "Товар з таким SKU або slug вже існує" },
          { status: 409 }
        );
      }
      throw error;
    }
  }

  // Недосяжно: цикл завжди або повертає відповідь, або кидає помилку.
  return NextResponse.json({ error: "Не вдалося зберегти товар" }, { status: 500 });
}
